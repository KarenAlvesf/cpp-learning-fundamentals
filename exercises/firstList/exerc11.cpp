/*
   11) Area of ​​a rectangle — Ask for width and height and calculate the area.
*/

#include <iostream>

using namespace std;

int main(){
    int width, height;

    cout << "Hi, please entry the width and height of the rectangle: \n\n";
    cin >> width >> height;

    cout << "\n The area of the rectangle is " << width * height << ".\n\n" << endl;

    return 0;

}